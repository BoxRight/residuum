//! Declaration association only; selecting a rule here is an explicit test
//! operation, not automatic activation of a verb by the forward engine.

use super::*;
use crate::surface::{FormalDeclaration, SurfaceRuleBody};
use crate::typed::{Type, Verb, VerbKind};
use crate::{elaborate_formal, parse_formal, parse_formal_to_typed};

const SOURCE: &str = include_str!("../../examples/experiments/sells_associated_program.res");
const BASELINE: &str = include_str!("../../examples/experiments/sells_program.res");

fn verb<'a>(module: &'a Module, name: &str) -> &'a Verb {
    module
        .declarations
        .iter()
        .find_map(|d| match d {
            Declaration::Verb(v) if v.name == name => Some(v),
            _ => None,
        })
        .unwrap()
}

fn rule<'a>(module: &'a Module, name: &str) -> &'a Rule {
    module
        .declarations
        .iter()
        .find_map(|d| match d {
            Declaration::Rule(r) if r.name == name => Some(r),
            _ => None,
        })
        .unwrap()
}

fn reference_source(target: &str) -> String {
    SOURCE.replace("program sellsProgram", &format!("program {target}"))
}

#[test]
fn verb_program_reference_is_typed_and_beta_paths_preserve_sells_behavior() {
    let surface = parse_formal(SOURCE).unwrap();
    assert_eq!(surface, crate::formal::parse_formal_manual(SOURCE).unwrap());
    let module = elaborate_formal(surface.clone()).unwrap();
    let baseline = parse_formal_to_typed(BASELINE).unwrap();
    let sales = verb(&module, "sells");
    assert_eq!(sales.kind, VerbKind::Seeded);
    assert_eq!(sales.args, verb(&baseline, "sells").args);
    assert_eq!(verb(&baseline, "sells").program, None);
    let reference = sales.program.as_ref().unwrap();
    assert_eq!(reference.name, "sellsProgram");
    let associated = rule(&module, &reference.name);
    assert_eq!(associated, rule(&baseline, "sellsProgram"));
    assert_eq!(
        associated
            .parameters
            .iter()
            .map(|p| p.ty.clone())
            .collect::<Vec<_>>(),
        sales
            .args
            .iter()
            .map(|p| p.ty.clone())
            .chain([Type::PropositionTime])
            .collect::<Vec<_>>()
    );

    // Follow the AST link and pass its name to the EXISTING rule-application
    // production. This substitutes the source-defined constant juan via elab's
    // existing beta-reduction, never a sells -> rule lookup table in Rust.
    let mut via_link = surface;
    let application = via_link
        .declarations
        .iter_mut()
        .find_map(|d| match d {
            FormalDeclaration::Rule(r) if r.name == "juanSale" => Some(&mut r.body),
            _ => None,
        })
        .unwrap();
    let SurfaceRuleBody::Application { rule: target, .. } = application else {
        unreachable!()
    };
    *target = reference.name.clone();
    let linked_specialization = elaborate_formal(via_link).unwrap();
    assert_eq!(
        rule(&linked_specialization, "juanSale"),
        rule(&baseline, "juanSale")
    );
    assert_eq!(
        rule(&linked_specialization, "juanSale").parameters,
        associated.parameters[1..]
    );

    let expected = run_experiments(&baseline).unwrap();
    let actual = run_experiments(&linked_specialization).unwrap();
    assert_eq!(actual, expected);
    // Event identity omits operational metadata. Check it separately when
    // claiming preservation of proposition kind and state transition times.
    for (a, b) in actual.iter().zip(&expected) {
        for (event, other) in a.closure.known.iter().zip(&b.closure.known) {
            assert_eq!(event.proposition, other.proposition);
            assert_eq!(event.transition, other.transition);
        }
        for (proof, other) in a.closure.derivations.iter().zip(&b.closure.derivations) {
            assert_eq!(proof.event.proposition, other.event.proposition);
            assert_eq!(proof.event.transition, other.event.transition);
            for (witness, compared) in proof
                .record
                .antecedents
                .iter()
                .zip(&other.record.antecedents)
            {
                assert_eq!(witness.proposition, compared.proposition);
                assert_eq!(witness.transition, compared.transition);
            }
        }
    }
    // Explicitly select the referenced lambda for a forward comparison. The
    // downstream rules are ordinary declarations, not generated by association.
    for experiment in &actual {
        let selected: Vec<_> = linked_specialization
            .declarations
            .iter()
            .filter_map(|d| match d {
                Declaration::Rule(r) if r.name != associated.name => Some(r.clone()),
                _ => None,
            })
            .chain([associated.clone()])
            .collect();
        let compared = close(
            experiment.experiment.input.clone(),
            &selected,
            &mut Clock::default(),
        );
        assert_eq!(
            compared.known.iter().cloned().collect::<BTreeSet<_>>(),
            experiment.closure.known.iter().cloned().collect()
        );
        assert_eq!(
            compared.derivations.len(),
            experiment.closure.derivations.len()
        );
        assert!(compared.derivations.iter().all(|d| {
            experiment
                .closure
                .derivations
                .iter()
                .any(|other| other.event == d.event && other.record == d.record)
        }));
    }
}

#[test]
fn associated_program_rejects_unresolved_ambiguous_or_incompatible_rule_signatures() {
    for target in ["missingProgram", "juan", "give"] {
        let error = parse_formal_to_typed(&reference_source(target)).unwrap_err();
        assert!(error.to_string().contains("unknown associated rule"));
    }
    let wrong_order = format!(
        "{}\nrule wrongOrder(object, seller, buyer, t) = sells(seller, object, buyer) @ t <= give(seller, object, buyer) @ after t",
        reference_source("wrongOrder")
    );
    let no_time = format!(
        "{}\nrule noTime(seller, object, buyer) = sells(seller, object, buyer) @ tau <= give(seller, object, buyer) @ after tau",
        reference_source("noTime")
    );
    let time_first = format!(
        "{}\nrule timeFirst(t, seller, object, buyer) = sells(seller, object, buyer) @ t <= give(seller, object, buyer) @ after t",
        reference_source("timeFirst")
    );
    for source in [
        reference_source("juanSale"),
        reference_source("ownsProgram"),
        wrong_order,
        no_time,
        time_first,
    ] {
        assert_eq!(
            parse_formal(&source).unwrap(),
            crate::formal::parse_formal_manual(&source).unwrap()
        );
        let error = parse_formal_to_typed(&source).unwrap_err();
        assert!(error.to_string().contains("has parameter types"), "{error}");
    }
    let ambiguous = format!(
        "{SOURCE}\nrule sellsProgram(seller, object, buyer, t) = sells(seller, object, buyer) @ t <= give(seller, object, buyer) @ after t"
    );
    assert!(
        parse_formal_to_typed(&ambiguous)
            .unwrap_err()
            .to_string()
            .contains("ambiguous associated rule")
    );
    for source in [
        SOURCE.replace("program sellsProgram", "program"),
        SOURCE.replace("program sellsProgram", "sellsProgram"),
    ] {
        assert!(parse_formal(&source).is_err());
    }
}

#[test]
fn association_keeps_verb_kinds_passive_and_can_reference_a_beta_specialized_lambda() {
    let mut declarations = parse_formal(SOURCE).unwrap();
    declarations
        .declarations
        .retain(|d| !matches!(d, FormalDeclaration::Experiment(_)));
    for (surface_kind, expected_kind) in [
        (crate::surface::SurfaceVerbKind::Seeded, VerbKind::Seeded),
        (crate::surface::SurfaceVerbKind::Derived, VerbKind::Derived),
        (crate::surface::SurfaceVerbKind::Effect, VerbKind::Effect),
    ] {
        let mut input = declarations.clone();
        let v = input
            .declarations
            .iter_mut()
            .find_map(|d| match d {
                FormalDeclaration::Verb(v) if v.name == "sells" => Some(v),
                _ => None,
            })
            .unwrap();
        v.kind = surface_kind;
        let result = elaborate_formal(input).unwrap();
        assert_eq!(verb(&result, "sells").kind, expected_kind);
        assert_eq!(
            verb(&result, "sells").is_abducible(),
            expected_kind == VerbKind::Seeded
        );
        assert_eq!(
            verb(&result, "sells").program.as_ref().unwrap().name,
            "sellsProgram"
        );
    }
    // A partially applied target needs a declaration with its residual signature.
    // No behavior/activation of this extra verb is asserted in this typing test.
    let narrow = format!(
        "{SOURCE}\nseeded verb juanSells(object : Thing, recipient : Person) = program juanSale"
    );
    let result = parse_formal_to_typed(&narrow).unwrap();
    assert_eq!(
        verb(&result, "juanSells").program.as_ref().unwrap().name,
        "juanSale"
    );
    assert_eq!(
        rule(&result, "juanSale")
            .parameters
            .iter()
            .map(|p| p.ty.clone())
            .collect::<Vec<_>>(),
        [
            Type::Entity("Thing".into()),
            Type::Entity("Person".into()),
            Type::PropositionTime
        ]
    );
    let experiments = run_experiments(&parse_formal_to_typed(SOURCE).unwrap()).unwrap();
    let real = experiments
        .iter()
        .find(|e| e.experiment.name == "real")
        .unwrap();
    let no_rules = close(real.experiment.input.clone(), &[], &mut Clock::default());
    assert_eq!(no_rules.known, real.experiment.input);
    assert!(
        no_rules.derivations.is_empty(),
        "association introduces no automatic rule loading"
    );

    // Effect state operations and declaration association coexist independently.
    let effect_source = SOURCE.replace(
        "recipient.assets += object",
        "recipient.assets += object\n    = program sellsProgram",
    );
    let effect_module = parse_formal_to_typed(&effect_source).unwrap();
    assert_eq!(
        verb(&effect_module, "give").effect,
        verb(&parse_formal_to_typed(SOURCE).unwrap(), "give").effect
    );
    assert_eq!(
        verb(&effect_module, "give").program.as_ref().unwrap().name,
        "sellsProgram"
    );
}
