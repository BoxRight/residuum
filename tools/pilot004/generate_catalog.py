"""Deterministic generator of the Pilot 004 candidate catalogue.

Writes docs/legal-geometry/pilot-004/frozen/catalog_<head>.res (Formal rules,
one module per head so that each module graph stays within the 64 KiB source
budget of the resolver) and
descriptions.tsv (initial deterministic descriptions d0). The grammar is fixed
in docs/pilot-004-contract.md section 4; the generator neither reads nor
anticipates valuations. Run: python3 -B tools/pilot004/generate_catalog.py
"""
from itertools import combinations
from pathlib import Path

FROZEN = Path(__file__).resolve().parents[2] / "docs/legal-geometry/pilot-004/frozen"
HEADS = ["prohibition", "permission", "obligation"]
ROLES = ["s", "b", "x"]
CONDITIONS = ["allergic", "visuallyImpaired"]
KINDS = ["animal", "food"]
PAIRS = [("s", "b"), ("s", "x"), ("b", "x")]
GLOSS = {
    "allergic": "an allergy",
    "visuallyImpaired": "a visual impairment",
    "animal": "an animal",
    "food": "food or drink",
}
HEAD_TEXT = {
    "prohibition": "a prohibition holds on the subject performing that conduct with that thing towards the beneficiary",
    "permission": "a permission holds for the subject performing that conduct with that thing towards the beneficiary",
    "obligation": "an obligation holds on the subject to perform that conduct with that thing towards the beneficiary",
}


def literals():
    out = []
    for v in ROLES:
        for k in CONDITIONS:
            for neg in (False, True):
                out.append(("condition", (v, k), neg))
    for k in KINDS:
        for neg in (False, True):
            out.append(("kind", ("o", k), neg))
    for pair in PAIRS:
        for neg in (False, True):
            out.append(("copresent", pair, neg))
    return out


def admissible(body):
    atoms = [(verb, args) for verb, args, _ in body]
    if len(set(atoms)) < len(atoms):
        return False  # an atom with both polarities (H4)
    uses_x = any("x" in args for _, args, _ in body)
    linked = any(verb == "copresent" and "x" in args for verb, args, _ in body)
    return linked or not uses_x  # the third party is linked by copresence (H3)


def formal(lit):
    verb, args, neg = lit
    return f"{'~' if neg else ''}{verb}({', '.join(args)}) @ t"


def role(v, seen):
    if v == "s":
        return "the subject"
    if v == "b":
        return "the beneficiary"
    if v in seen:
        return "X"
    seen.add(v)
    return "a person X"


def text(lit, seen):
    verb, args, neg = lit
    if verb == "condition":
        who = role(args[0], seen)
        return (f"there is explicit evidence that {who} does not have the condition {GLOSS[args[1]]}"
                if neg else f"{who} has the condition {GLOSS[args[1]]}")
    if verb == "kind":
        return (f"there is explicit evidence that the thing is not {GLOSS[args[1]]}"
                if neg else f"the thing is {GLOSS[args[1]]}")
    first, second = role(args[0], seen), role(args[1], seen)
    return (f"there is explicit evidence that {first} and {second} are not in the same place"
            if neg else f"{first} and {second} are in the same place")


def main():
    lits = literals()
    bodies = [b for n in (1, 2) for b in combinations(lits, n) if admissible(b)]
    rules = {head: [] for head in HEADS}
    rows = ["id\thead\tbody\td0"]
    index = 0
    for head in HEADS:
        for body in bodies:
            index += 1
            name = f"p4c{index:03d}"
            uses_x = any("x" in args for _, args, _ in body)
            params = ["a", "s", "c", "o", "b", "au", "e"] + (["x"] if uses_x else []) + ["t"]
            antecedent = " & ".join(["Act(a, s, c, o, b, au, e) @ t"] + [formal(l) for l in body])
            rules[head].append(
                f"rule {name}({', '.join(params)}) =\n    {antecedent}\n"
                f"    <= {head}(hypNorm, s, c, o, b, administrative, hypEnacted) @ t\n"
            )
            seen = set()
            clauses = [text(l, seen) for l in body]
            d0 = ("If an act is recorded in which the subject performs a conduct with a thing for a beneficiary, and "
                  + ", and ".join(clauses) + f", then {HEAD_TEXT[head]}.")
            rows.append(f"{name}\t{head}\t{' & '.join(formal(l) for l in body)}\t{d0}")
    for head in HEADS:
        header = (
            f"module Pilot004Catalog_{head}\n\nimport \"./vocabulary.res\"\n\n"
            "// Generated by tools/pilot004/generate_catalog.py. Every admissible clause\n"
            f"// of the Pilot 004 grammar with head {head} and one or two antecedents\n"
            "// besides the act anchor. Never load these rules as one theory: each\n"
            "// candidate is evaluated in isolation as LegalGeneral + vocabulary + one rule.\n\n"
        )
        (FROZEN / f"catalog_{head}.res").write_text(header + "\n".join(rules[head]))
    (FROZEN / "descriptions.tsv").write_text("\n".join(rows) + "\n")
    print(len(bodies), index)


if __name__ == "__main__":
    main()
